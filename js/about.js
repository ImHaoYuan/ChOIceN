  /* ---------------------------------------------------------
     渲染
     --------------------------------------------------------- */
  function renderBlock(b) {
    if (b.p != null) return el('p.about__p', { text: b.p });
    if (b.h != null) return el('h3.about__sub', { text: b.h });
    if (b.note != null) return el('p.about__note', { text: b.note });
    if (b.ul) {
      return el('ul.about__list', b.ul.map(function (t) { return el('li', { text: t }); }));
    }
    if (b.dl) {
      const kids = [];
      b.dl.forEach(function (pair) {
        kids.push(el('dt.about__term', { text: pair[0] }));
        kids.push(el('dd.about__desc', { text: pair[1] }));
      });
      return el('dl.about__dl', kids);
    }
    if (b.link) {
      // 外链一律新开标签页并带上 noopener：GitHub Pages 是 https，
      // 站内链接则全部走 hash 路由，不写任何绝对路径，换域名/子路径都不用改。
      return el('p.about__link', [el('a', {
        href: b.link.href,
        target: '_blank',
        rel: 'noopener noreferrer',
        text: b.link.text
      })]);
    }
    return null;
  }

  function renderSection(section, index) {
    const head = el('h2.about__title', { text: section.title });
    const body = section.blocks.map(renderBlock).filter(Boolean);
    return el('section.panel.about__section', {
      dataset: { section: String(index + 1) }
    }, [head].concat(body));
  }

